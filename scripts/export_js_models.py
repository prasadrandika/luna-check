"""Write models.json as a browser script for the website's JS port.

    python scripts/export_js_models.py path/to/website/js/luna-models.js
"""

import json
import sys
from pathlib import Path

DATA = Path(__file__).resolve().parent.parent / "src" / "luna_check" / "data" / "models.json"


def main(argv=None) -> int:
    argv = argv if argv is not None else sys.argv[1:]
    if len(argv) != 1:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    data = json.loads(DATA.read_text(encoding="utf-8"))
    body = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    Path(argv[0]).write_text(
        "/* Model retirement data from luna-check (MIT, https://github.com/prasadrandika/luna-check),\n"
        " * data/models.json: built from each provider's official deprecation page.\n"
        " * Generated by scripts/export_js_models.py. Do not edit by hand. */\n"
        f"window.LUNA_MODELS = {body};\n",
        encoding="utf-8",
    )
    print(f"wrote {argv[0]} ({len(data['models'])} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
