"""Model retirement data (data/models.json) and how LC001 reports it.

models.json is generated by scripts/build_models.py from each provider's
official deprecation page. Every entry carries its source URL.

Some IDs exist on two platforms with different dates:
  - OpenAI and Azure OpenAI (gpt-4o, o3, ...). Azure dates are used only when
    the file talks to Azure OpenAI; Azure code usually names a deployment, so
    a bare name there can mean several model versions.
  - The Gemini API and Vertex AI (gemini-2.5-pro, ...). The platform the file
    uses wins. When the file shows neither, the Gemini API entry is reported
    with a note about Vertex AI.
"""

from __future__ import annotations

import datetime as dt
import json
import os
import re
from pathlib import Path

DATA = Path(__file__).parent / "data" / "models.json"

LABEL = {
    "openai": "OpenAI API",
    "anthropic": "Claude API",
    "gemini-api": "Gemini API",
    "vertex": "Vertex AI",
    "azure": "Azure OpenAI",
    "bedrock": "Amazon Bedrock",
}
# When a file shows no platform, an ID shared by two platforms uses the first.
DEFAULT_OF = {"azure": "openai", "vertex": "gemini-api"}
# Shared-ID platforms that get a "(on X: ...)" note when the file shows neither.
NOTE_PLATFORMS = {"vertex"}

# Markers that show which platform a file talks to.
CONTEXT = {
    "azure": re.compile(
        r"\bAzureOpenAI\b|\bAsyncAzureOpenAI\b|\bAzureChatOpenAI\b|\bAzureOpenAIEmbeddings\b|"
        r"\bazure_endpoint\b|\bazureEndpoint\b|\bAZURE_OPENAI|\.openai\.azure\.com|\bazopenai\b|"
        r"openai/azure|@azure/openai|\bazure_deployment\b|\bdeployment_name\b"
    ),
    "vertex": re.compile(
        r"\bvertexai\b|\bvertex_ai\b|\bVertexAI\b|\bChatVertexAI\b|\baiplatform\b|"
        r"GOOGLE_GENAI_USE_VERTEXAI|vertexai\s*[=:]\s*(?:True|true)|@google-cloud/vertexai|"
        r"cloud\.google\.com/go/vertexai|aiplatform\.googleapis\.com|gemini-enterprise-agent-platform"
    ),
    "gemini-api": re.compile(
        r"google\.generativeai|\bChatGoogleGenerativeAI\b|generativelanguage\.googleapis\.com|"
        r"\bGEMINI_API_KEY\b|@google/generative-ai|github\.com/google/generative-ai-go|"
        r"genai\.Client\(\s*api_key|GoogleGenAI\(\s*\{\s*apiKey"
    ),
}

BEDROCK_PREFIX = r"(?:(?:us|eu|apac|global|jp|au|ca|us-gov)\.)?"


def today() -> dt.date:
    """Today's date, or LUNA_CHECK_TODAY (YYYY-MM-DD) for reproducible runs."""
    env = os.environ.get("LUNA_CHECK_TODAY")
    return dt.date.fromisoformat(env) if env else dt.date.today()


def fmt(iso: str) -> str:
    d = dt.date.fromisoformat(iso)
    return f"{d:%b} {d.day}, {d.year}"


class Catalog:
    def __init__(self, data: dict):
        self.data = data
        self.index = {}  # id -> [(entry, is_alias)]
        for e in data["models"]:
            for i in e["ids"]:
                self.index.setdefault(i, []).append((e, False))
            for a in e.get("aliases", []):
                self.index.setdefault(a, []).append((e, True))
        keys = sorted(self.index, key=len, reverse=True)
        bedrock = [k for k in keys if all(en["platform"] == "bedrock" for en, _ in self.index[k])]
        generic = [k for k in keys if k not in set(bedrock)]
        alt_b = "|".join(re.escape(k) for k in bedrock) or "(?!x)x"
        alt_g = "|".join(re.escape(k) for k in generic) or "(?!x)x"
        self.regex = re.compile(
            rf"(?<![\w.-])(?:{BEDROCK_PREFIX}(?P<b>{alt_b})|(?P<g>{alt_g}))(?![\w.-])"
        )

    def find(self, s: str):
        """Yield (match start, model id) for every listed model ID in s."""
        for m in self.regex.finditer(s):
            key = m.group("b") or m.group("g")
            yield m.start(), key


_CATALOG = None


def catalog() -> Catalog:
    global _CATALOG
    if _CATALOG is None:
        _CATALOG = Catalog(json.loads(DATA.read_text(encoding="utf-8")))
    return _CATALOG


def platforms_in(text: str) -> set:
    return {p for p, rx in CONTEXT.items() if rx.search(text)}


class Report:
    """What LC001 says about one model ID in one file."""

    def __init__(self, severity, message, fix, short, source, low_reason=""):
        self.severity = severity
        self.message = message
        self.fix = fix
        self.short = short
        self.source = source
        self.low_reason = low_reason
        self.replacement = None


def _pick(entries: list, context: set):
    """Choose the platform to report and the other platforms to note."""
    by_platform = {}
    for e, alias in entries:
        by_platform.setdefault(e["platform"], []).append((e, alias))
    platforms = set(by_platform)
    in_context = platforms & context
    if "azure" in context and platforms <= {"openai", "azure"}:
        # An Azure OpenAI file: only Azure's own schedule applies to its models.
        if "azure" not in platforms:
            return None, []
        platform = "azure"
    elif in_context:
        platform = sorted(in_context)[0]
    else:
        # No platform shown: Azure needs an Azure file, and a shared ID uses
        # its default platform (Gemini API over Vertex AI).
        cands = [p for p in platforms
                 if p != "azure" and not (p in DEFAULT_OF and DEFAULT_OF[p] in platforms)]
        if not cands:
            return None, []
        platform = sorted(cands)[0]
    notes = [] if in_context else [p for p in platforms if p in NOTE_PLATFORMS and p != platform]
    return (platform, by_platform[platform]), [(p, by_platform[p]) for p in notes]


def _latest(entries: list):
    """A duplicate ID on one platform: the later notice is the real shutdown."""
    return max(entries, key=lambda ea: ea[0]["shutdown"] or "")


def _regions(groups: list, now: str) -> str:
    parts = []
    for g in groups:
        regs = g["regions"]
        where = ", ".join(regs) if len(regs) <= 4 else f"{len(regs)} regions"
        verb = "reached end of life on" if g["date"] < now else "reaches end of life on"
        parts.append(f"{verb} {fmt(g['date'])} in {where}")
    return "; ".join(parts)


def describe(model_id: str, context: set):
    """A Report for model_id, or None when it is not listed for this context."""
    entries = catalog().index.get(model_id)
    if not entries:
        return None
    picked, notes = _pick(entries, context)
    if picked is None:
        return None
    platform, chosen = picked
    now = today().isoformat()
    label = LABEL[platform]
    tag = "" if platform == "openai" else f" ({label})"

    if platform == "azure" and any(alias for _, alias in chosen):
        return _azure_versions(model_id, chosen, now)

    e, alias = _latest(chosen)
    repl = e.get("replacement")
    quoted = " or ".join(f'"{r}"' for r in repl.split(" or ")) if repl else ""
    use = f" Replace it with {quoted}." if repl else ""
    fix = f"Use {quoted} (or read the model name from config)." if repl else \
        "Move to a model the provider still supports."
    src = e["source"]
    date = e.get("shutdown")

    if alias:
        target = ", ".join(e["ids"])
        subject = f'"{model_id}" points to the dated snapshot(s) {target}, which'
    else:
        subject = f'"{model_id}"'

    if e.get("regions"):
        msg = f'On {label}, "{model_id}" {_regions(e["regions"], now)}.'
        if any(g["date"] >= now for g in e["regions"]):
            msg += " The Bedrock page names no replacement; move to an Active model."
        short = f'"{model_id}" Bedrock end of life from {fmt(e["regions"][0]["date"])}'
        rep = Report("high", msg, "Move to an Active Bedrock model in your Region.", short, src)
    elif date is None:
        msg = f'"{model_id}" is deprecated{tag}, and no shutdown date has been announced yet.{use}'
        rep = Report("low", msg, fix, f'"{model_id}" deprecated, no date yet', src, "no date yet")
    elif e.get("after_shutdown") == "routes":
        target = e.get("routes_to")
        if date >= now:
            msg = (f'From {fmt(date)}, requests to "{model_id}" on the {label} are routed to '
                   f'"{target}" and billed at its rates. The {label} page says to review the '
                   "breaking API changes before then.")
            short = f'"{model_id}" routed to {target} from {fmt(date)}'
            rep = Report("high", msg, f"Move to {quoted or repr(target)} and test it before {fmt(date)}.", short, src)
        else:
            msg = f'Since {fmt(date)}, requests to "{model_id}" on the {label} are served by "{target}".'
            short = f'"{model_id}" served by {target} since {fmt(date)}'
            rep = Report("low", msg, f'Use "{repl or target}" directly.', short, src, "routed to a newer model")
    elif date >= now:
        verb = "shut down" if alias else "shuts down"
        msg = f"{subject} {verb} on {fmt(date)}{tag}.{use}"
        short = f'"{model_id}" shuts down on {fmt(date)}' + (f" -> {repl}" if repl else "")
        rep = Report("high", msg, fix, short, src)
    else:
        verb = "were shut down" if alias else "was shut down"
        msg = f"{subject} {verb} on {fmt(date)}{tag}, so requests to it fail.{use}"
        short = f'"{model_id}" shut down on {fmt(date)}' + (f" -> {repl}" if repl else "")
        rep = Report("high", msg, fix, short, src)

    rep.replacement = repl
    for p, others in notes:
        o, _ = _latest(others)
        od = o.get("shutdown")
        if od:
            state = f"retired {fmt(od)}" if od < now else f"retires {fmt(od)}"
            rep.message += f" On {LABEL[p]}: {state}."
    return rep


def _azure_versions(model_id: str, chosen: list, now: str) -> Report:
    by_date = {}
    for e, _ in chosen:
        by_date.setdefault(e["shutdown"], []).append(e["version"])
    parts = []
    for date in sorted(by_date):
        vs = ", ".join(sorted(by_date[date]))
        word = "version" if len(by_date[date]) == 1 else "versions"
        many = len(by_date[date]) > 1
        verb = ("were retired on" if many else "was retired on") if date < now else \
            ("retire on" if many else "retires on")
        parts.append(f"{word} {vs} {verb} {fmt(date)}")
    repls = sorted({e["replacement"] for e, _ in chosen if e.get("replacement")})
    msg = f'On Azure OpenAI, "{model_id}" {"; ".join(parts)}. Check which version your deployment uses.'
    if repls:
        msg += f' Listed replacement: {" or ".join(repls)}.'
    first = min(by_date)
    short = f'"{model_id}" Azure retirement from {fmt(first)}'
    rep = Report("high", msg, "Upgrade the deployment to a supported model version.", short, chosen[0][0]["source"])
    rep.replacement = repls[0] if repls else None
    return rep
